const aiConfig = require('../../config/arena-ai.json');
const { providerStatus, completeChatWithRetry } = require('../ai/provider');
const { httpError } = require('./times');
const { getEventRules, getStrategy, getHistoryItem, latestReadiness, q, ready } = require('./arenaService');
const { simulationEngine } = require('./engine');

const CONTEXTS = new Set(aiConfig.contexts);
const hits = new Map();

function allowRequest(userId) {
    const now = Date.now();
    const windowMs = aiConfig.rateLimit.windowMs;
    const max = aiConfig.rateLimit.maxRequests;
    const recent = (hits.get(userId) || []).filter((at) => now - at < windowMs);
    if (recent.length >= max) return false;
    recent.push(now);
    hits.set(userId, recent);
    return true;
}

function systemPrompt() {
    return [
        'You explain approved ROXCLUB Arena data for an authenticated athlete.',
        'Use only the JSON facts provided. Do not invent distances, repetitions, finish times, DNA weights, or rankings.',
        'Do not diagnose injury or prescribe rehab. Do not change race rules.',
        'If a value is missing, say it is unavailable. Keep the answer under 180 words.',
        'Goal time and running pace are independent stored targets, not a calculated prediction.',
    ].join(' ');
}

function deterministicExplanation(context, facts) {
    if (context === 'race_rules') {
        const names = (facts.stations || []).map((row) => row.title).join(', ');
        return `This event uses a fixed ROXCLUB station order${names ? `: ${names}` : ''}. Distances, repetitions, and movement standards come from the published event version. They are not generated by AI.`;
    }
    if (context === 'goal_and_pace') {
        const goal = facts.goalTime?.clock || 'not set';
        const pace = facts.runPace?.clock ? `${facts.runPace.clock} min/km` : 'not set';
        return `Your saved target finish is ${goal}. Your saved run pace is ${pace}. These are athlete-entered targets stored separately. ROXCLUB does not currently reconcile them with an approved pacing model, and they are not a guaranteed race prediction.`;
    }
    if (context === 'strategy') {
        const pacing = facts.pacingStrategy || 'target';
        const count = Object.keys(facts.stationTargets || {}).length;
        return `Your race plan uses the ${pacing} pacing selection with ${count} station target${count === 1 ? '' : 's'} on the published course order. Checkpoint choices Hold, Push, and Back Off are athlete decisions. The Virtual Race Engine is not enabled, so no fatigue or predicted split is calculated.`;
    }
    if (context === 'readiness') {
        if (!facts.readiness) {
            return 'No current readiness record is stored for this athlete. Missing wearable data does not lower athletic ability. Readiness is current state, not Athlete DNA.';
        }
        return `Your latest stored readiness status is ${facts.readiness.status || 'unavailable'}${facts.readiness.score == null ? '' : ` with score ${facts.readiness.score}`}. This is current state, not permanent ability, and it does not change XP or official race rankings.`;
    }
    const status = facts.raceStatus || 'unknown';
    const finish = facts.finishTime?.clock || 'not recorded';
    const official = facts.officialCompleted ? 'official competitive result' : 'not an official competitive result';
    return `This race session is ${status}. Recorded elapsed time is ${finish}. Evidence source is ${facts.evidenceSource || 'unavailable'}. This record is ${official}. A virtual session does not create real-world Athlete DNA evidence.`;
}

async function loadFacts(userId, context, body, options) {
    await ready(options);
    if (context === 'race_rules') {
        const eventId = String(body?.eventId || '').trim();
        if (!eventId) throw httpError('EVENT_REQUIRED', 400, 'eventId is required for race_rules');
        const rules = await getEventRules(eventId, options);
        return {
            eventId: rules.eventId,
            title: rules.title,
            aboutRules: rules.aboutRules,
            generalRules: rules.generalRules,
            stations: rules.stations.map((row) => ({
                title: row.title,
                value: row.value,
            })),
        };
    }
    if (context === 'goal_and_pace' || context === 'strategy') {
        const eventId = String(body?.eventId || '').trim();
        if (!eventId) throw httpError('EVENT_REQUIRED', 400, 'eventId is required for this explanation');
        const strategy = await getStrategy(userId, eventId, options);
        return {
            eventId,
            goalTime: strategy.goalTime,
            runPace: strategy.runPace,
            pacingStrategy: strategy.pacingStrategy,
            stationTargets: strategy.stationTargets,
            validation: strategy.validation,
            predictionAvailable: false,
        };
    }
    if (context === 'readiness') {
        const query = q(options);
        const readiness = await latestReadiness(userId, query);
        return {
            readiness: readiness
                ? {
                      status: readiness.status,
                      score: readiness.score == null ? null : Number(readiness.score),
                      confidence: readiness.confidence || null,
                      localDate: readiness.local_date || null,
                  }
                : null,
        };
    }
    const sessionId = String(body?.sessionId || body?.id || '').trim();
    if (!sessionId) throw httpError('SESSION_REQUIRED', 400, 'sessionId is required for race_summary');
    const item = await getHistoryItem(userId, sessionId, options);
    return {
        sessionId: item.id,
        raceStatus: item.raceStatus,
        finishTime: item.finishTime,
        officialCompleted: item.officialCompleted,
        resultStatus: item.resultStatus,
        evidenceSource: item.evidenceSource,
        eventName: item.eventName,
    };
}

function sourceAvailability(facts) {
    return {
        eventRules: Boolean(facts.stations),
        goalTime: Boolean(facts.goalTime?.milliseconds),
        runPace: Boolean(facts.runPace?.millisecondsPerKm),
        strategy: Boolean(facts.pacingStrategy),
        readiness: Boolean(facts.readiness),
        raceResult: Boolean(facts.sessionId),
        athleteDna: false,
        stationProficiency: false,
        virtualRaceEngine: false,
    };
}

async function explainArena(userId, body, options = {}) {
    const context = String(body?.context || '').trim();
    if (!CONTEXTS.has(context)) {
        throw httpError(
            'INVALID_CONTEXT',
            400,
            'context must be race_rules, goal_and_pace, strategy, readiness, or race_summary'
        );
    }
    if (!allowRequest(userId)) {
        throw httpError('RATE_LIMITED', 429, 'Too many Arena explanation requests');
    }
    const facts = await loadFacts(userId, context, body || {}, options);
    const template = deterministicExplanation(context, facts);
    const status = providerStatus(options.env);
    const payload = {
        available: status.available,
        provider: status.provider,
        modelVersion: status.model,
        context,
        explanation: template,
        generation: 'deterministic_template',
        limitations: aiConfig.limitations,
        sourceData: sourceAvailability(facts),
        simulationEngine: simulationEngine(),
        facts,
    };
    if (!status.available) {
        payload.unavailable = {
            code: status.reason,
            message: status.message,
        };
        return payload;
    }
    try {
        const generated = await completeChatWithRetry({
            system: systemPrompt(),
            user: JSON.stringify({ context, facts }),
            timeoutMs: aiConfig.timeoutMs,
            env: options.env,
            fetchImpl: options.fetchImpl,
        });
        payload.explanation = generated.text;
        payload.generation = 'model';
        payload.modelVersion = generated.model;
        return payload;
    } catch (error) {
        payload.generation = 'deterministic_fallback';
        payload.unavailable = {
            code: error.code || 'AI_PROVIDER_FAILED',
            message: 'The model explanation is unavailable. The approved stored values are shown instead.',
        };
        return payload;
    }
}

module.exports = {
    explainArena,
    deterministicExplanation,
    CONTEXTS,
};
